"""Generate optional TCE2 voice DMS from NavStudio's native command catalog.

The public mod stays unchanged. Each editor page fits the native menu parser.
"""
from pathlib import Path
import re
from botmenu import catalog

HEADER = '// Generated by build_botmenu.py; edit the shared native catalog.\n#include "ui/menudef.h"\n'


def button(name, label, y, action, key=None):
    item=('itemDef { name "'+name+'" rect 12 '+str(y)+' 588 22 type ITEM_TYPE_BUTTON text "'+label+
          '" textscale .23 textaligny 16 forecolor 1 1 1 1 visible 1 action { '+action+' } }')
    return item+('\nexecKey "'+key+'" { '+action+' }' if key else '')


def page(name, title, buttons, back=None, extras=()):
    result=[HEADER,'menuDef { name "'+name+'" rect 106 30 612 420 visible 0 fullscreen 0 style WINDOW_STYLE_FILLED backcolor .04 .04 .04 .94',
            'onOpen { setCvar cl_bypassMouseInput "0" ; }',
            'onESC { uiScript closeingame ; }',
            'itemDef { name "title" rect 12 8 588 24 text "'+title+'" textscale .28 textaligny 18 forecolor 1 .8 .3 1 visible 1 decoration }']
    result.extend(buttons)
    result.extend(extras)
    if back:
        result.append(button('back','V. Back / Zurueck',358,'close '+name+' ; open '+back+' ;','v'))
    result.append(button('close','Z. Close / Schliessen',392,'uiScript closeingame ;','z'))
    result.append('}')
    return '\n'.join(result)+'\n'


def render_files():
    groups={}
    for action in catalog('tce2')['actions']:
        groups.setdefault(action['group'],[]).append(action)
    files={}
    roots=[('tce_omnibot' if i==0 else 'tce_ob_root_'+str(i)) for i in range((len(groups)+9)//10)]
    names=[]
    for i,(group,actions) in enumerate(groups.items()):
        first='tce_ob_'+str(i)+'_0'; names.append((group,first))
        for start in range(0,len(actions),10):
            number=start//10; name='tce_ob_'+str(i)+'_'+str(number)
            buttons=[]
            for j,a in enumerate(actions[start:start+10]):
                key=str((j+1)%10)
                cmd='exec "bot '+a['command']+'" ;'
                if a['confirm']:
                    confirm=name+'_'+str(j)+'_confirm'
                    cmd='close '+name+' ; open '+confirm+' ;'
                    files[confirm+'.menu']=page(confirm,'Confirm / Bestaetigen',[
                        button('apply',a['label'],80,'exec "bot '+a['command']+'" ; close '+confirm+' ; open '+name+' ;','1')],name)
                buttons.append(button(a['id'],key+'. '+a['label'],38+j*26,cmd,key))
            # Controls never overlap the ten command rows.
            if number:
                buttons.append(button('previous','-. Previous page / Vorherige Seite',330,
                                      'close '+name+' ; open tce_ob_'+str(i)+'_'+str(number-1)+' ;','-'))
            if start+10<len(actions):
                buttons.append(button('next','= . Next page / Naechste Seite',330 if not number else 302,
                                      'close '+name+' ; open tce_ob_'+str(i)+'_'+str(number+1)+' ;','='))
            files[name+'.menu']=page(name,group+' '+str(number+1),buttons,roots[i//10])
    for index,root in enumerate(roots):
        items=[button('group'+str(j),str((j+1)%10)+'. '+label,38+j*28,
                      'close '+root+' ; open '+name+' ;',str((j+1)%10))
               for j,(label,name) in enumerate(names[index*10:index*10+10])]
        items.append(button('names','N. Names / Namen',330,'close '+root+' ; open tce_ob_names ;','n'))
        if len(roots)>1:
            items.append(button('next','= . More groups / Weitere Bereiche',358,
                                'close '+root+' ; open '+roots[(index+1)%len(roots)]+' ;','='))
        files[('tce_omnibot' if index==0 else root)+'.menu']=page(root,'TCE2 Omni-bot DMS / Voice editor',items)
    files['tce_ob_names.menu']=page('tce_ob_names','Names / Namen',[
        button('goal','1. Goal name / Goalname',65,'close tce_ob_names ; open tce_ob_goalname ;','1'),
        button('group','2. Goal group / Goalgruppe',105,'close tce_ob_names ; open tce_ob_groupname ;','2'),
        button('waypoint','3. Waypoint name / Wegpunktname',145,'close tce_ob_names ; open tce_ob_waypointname ;','3'),
        button('values','4. Custom numeric value / Eigener Zahlenwert',185,'close tce_ob_names ; open tce_ob_value ;','4')],roots[0])
    for kind,label,command in [('goalname','Goal name / Goalname','omnibot_goalname'),
                               ('groupname','Goal group / Goalgruppe','omnibot_goalgroup'),
                               ('waypointname','Waypoint name / Wegpunktname','omnibot_waypointname')]:
        name='tce_ob_'+kind
        field='itemDef { name "text" rect 12 70 588 28 type ITEM_TYPE_EDITFIELD cvar "ui_omnibotGoalName" maxChars 64 maxPaintChars 64 text "Name: " textscale .25 textaligny 18 forecolor 1 1 1 1 visible 1 }'
        files[name+'.menu']=page(name,label,[button('apply','Apply / Anwenden',125,'exec "'+command+'" ;')],
                                'tce_ob_names',extras=[field,'onEnter { exec "'+command+'" ; }'])
    value='itemDef { name "value" rect 12 65 588 28 type ITEM_TYPE_EDITFIELD cvar "ui_omnibotPropertyValue" maxChars 16 maxPaintChars 16 text "Value / Wert: " textscale .25 textaligny 18 forecolor 1 1 1 1 visible 1 }'
    files['tce_ob_value.menu']=page('tce_ob_value','Selected goal: numeric property',[
        button(prop,label,120+i*38,'exec "omnibot_goalproperty '+prop+'" ;')
        for i,(prop,label) in enumerate([('radius','Radius (0..999)'),('timeout','Timeout (0..5000 ms)'),
                                        ('mincamptime','Min. camp time (0..9999 s)'),('maxcamptime','Max. camp time (0..9999 s)')])],
        'tce_ob_names',extras=[value])
    if any(len(text.encode('ascii'))>=32768 for text in files.values()):
        raise ValueError('Generated menu exceeds the native parser limit.')
    return files


def render():
    """Root menu only; render_files returns the complete parser-sized pages."""
    return render_files()['tce_omnibot.menu']


def write_assets(target=None):
    target=Path(target) if target else Path(__file__).resolve().parent/'editor-ui'
    target.mkdir(parents=True,exist_ok=True)
    for filename,menu,key in [('wm_quickmessage.menu','wm_quickmessage','o'),
                              ('wm_quickmessageAlt.menu','wm_quickmessageAlt','8'),
                              ('wm_ftquickmessage.menu','wm_ftquickmessage','o'),
                              ('wm_ftquickmessageAlt.menu','wm_ftquickmessageAlt','8')]:
        file=target/filename;text=file.read_text()
        text=re.sub(r'onOpen\s*\{ setCvar cl_bypassMouseInput "[01]" \}',
                    'onOpen { setCvar cl_bypassMouseInput "0" }',text)
        text=re.sub(r'onEsc\s*\{ (?:closeAll|uiScript closeingame\s*;) \}',
                    'onEsc { uiScript closeingame ; }',text)
        pattern=r'(QM_MENU_START\( "'+menu+r'" \).*?)(QM_MENU_END)'
        def voice_entry(match):
            body=match[1]
            body=re.sub(r'\n\s*// The optional editor[^\n]*\n\s*QM_MENU_ITEM\([^\n]+\)\s*','\n',body)
            body=re.sub(r'\n\s*// BEGIN NAVSTUDIO VOICE ENTRY.*?// END NAVSTUDIO VOICE ENTRY\s*','\n',body,flags=re.S)
            action='close '+menu+' ; exec "omnibot_menu" ;'
            entry='\n// BEGIN NAVSTUDIO VOICE ENTRY\n'+(
                'itemDef { name "navstudio_voice_editor" rect 6 $evalfloat(35 + 12 * 7) 188 12 origin ORIGIN_QUICKMESSAGE '
                'type ITEM_TYPE_BUTTON text "^3'+key.upper()+'. TCE2 Omni-bot DMS" textfont UI_FONT_COURBD_21 '
                'textstyle ITEM_TEXTSTYLE_SHADOWED textscale .2 textaligny 8 forecolor .6 .6 .6 1 visible 1 '
                'action { '+action+' } }\nexecKey "'+key+'" { '+action+' }\n// END NAVSTUDIO VOICE ENTRY\n\n')
            return body+entry+match[2]
        text,count=re.subn(pattern,voice_entry,text,count=1,flags=re.S)
        if count!=1: raise ValueError('Optional voice root missing: '+filename)
        file.write_text(text,encoding='ascii')
    files=render_files()
    # Remove only stale generated pages, keeping maintained voice assets.
    for existing in target.glob('tce_ob_*.menu'):
        if existing.name not in files: existing.unlink()
    for name,text in files.items():
        (target/name).write_text(text,encoding='ascii')
    source=Path(__file__).resolve().parents[2]/'assets/ui'
    for name in ('menus.txt','menus_gt2.txt','menus_gt5.txt','menus_gt7.txt'):
        text=(source/name).read_text()
        marker='\n\t// Optional local voice DMS; never part of the public mod.\n'
        additions=''.join('\tloadMenu { "ui/'+file+'" }\n' for file in sorted(files))
        offset=text.rfind('}')
        if offset<0: raise ValueError('Missing base menu list closing brace.')
        (target/name).write_text(text[:offset]+marker+additions+text[offset:],encoding='ascii')
    members=set(files)|{'menus.txt','menus_gt2.txt','menus_gt5.txt','menus_gt7.txt',
                        'wm_quickmessage.menu','wm_quickmessageAlt.menu',
                        'wm_ftquickmessage.menu','wm_ftquickmessageAlt.menu'}
    (target/'editor-files.txt').write_text('\n'.join(sorted(members))+'\n',encoding='ascii')
    return files


if __name__=='__main__': write_assets()
